/**
 * Returns detailed places for a given destination ID.
 */
export function getDetailedPlacesForDestination(destId: string): DetailedPlace[] {
  if (!destId) return [];
  const lower = destId.trim().toLowerCase();
  const targetId = lower === 'thailand' || lower === 'th' ? 'bangkok' : lower;
  return DETAILED_CURATED_PLACES.filter(
    (p) => p.destinationId.toLowerCase() === lower || p.destinationId.toLowerCase() === targetId
  );
}

/**
 * Checks if a venue is open on a specific day of week (0=Sunday, 1=Monday, ..., 6=Saturday).
 */
export function isPlaceOpenOnDayOfWeek(place: DetailedPlace, dayOfWeek: number): boolean {
  if (!place.openingHours) return true; // Opening hours unrecorded -> treated as unknown/flexible
  const closedDays = place.openingHours.closedDays || [];
  return !closedDays.includes(dayOfWeek);
}
