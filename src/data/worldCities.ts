/**
 * Finds a catalog city by exact ID match.
 */
export function findCityById(id: string): WorldCityData | undefined {
  if (!id) return undefined;
  const lower = id.trim().toLowerCase();
  return WORLD_CITIES.find((c) => c.id.toLowerCase() === lower);
}

/**
 * Finds a catalog city by canonical name or verified alias (case-insensitive).
 */
export function findCityByNameOrAlias(query: string): WorldCityData | undefined {
  if (!query) return undefined;
  const lower = query.trim().toLowerCase();
  return WORLD_CITIES.find(
    (c) =>
      c.id.toLowerCase() === lower ||
      c.name.toLowerCase() === lower ||
      (c.aliases && c.aliases.some((a) => a.toLowerCase() === lower))
  );
}

/**
 * Searches cities by partial match across name, country, region, and aliases.
 */
export function searchWorldCities(query: string): WorldCityData[] {
  const lower = query.trim().toLowerCase();
  if (!lower) return [];
  return WORLD_CITIES.filter(
    (c) =>
      c.id.toLowerCase().includes(lower) ||
      c.name.toLowerCase().includes(lower) ||
      c.country.toLowerCase().includes(lower) ||
      c.region.toLowerCase().includes(lower) ||
      (c.aliases && c.aliases.some((a) => a.toLowerCase().includes(lower)))
  );
}

/**
 * Converts a verified WorldCityData entry into a typed Destination object.
 * Does not fabricate uncurated activities or itineraries.
 */
export function cityToDestination(city: WorldCityData): Destination {
  return {
    id: city.id,
    name: city.name,
    primaryCity: city.name,
    country: city.country,
    countryCode: city.countryCode,
    region: city.region,
    coordinates: { lat: city.lat, lng: city.lng },
    description: city.description || `City in ${city.country} with verified geographic coordinates.`,
    category: city.category || 'cultural',
    tags: [
      city.name.toLowerCase(),
      city.country.toLowerCase(),
      ...(city.aliases ? city.aliases.map((a) => a.toLowerCase()) : []),
    ],
    rating: 4.8,
    subtitle: `Explore ${city.name}`,
    arrivalMessage: `Welcome to ${city.name}, ${city.country}!`,
    landmarkSvgType:
      city.id === 'london'
        ? 'london'
        : city.id === 'new-york'
        ? 'newyork'
        : city.id === 'rome'
        ? 'rome'
        : 'generic',
  };
}
