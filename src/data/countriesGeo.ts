// Real World Country Boundary Dataset for Ryoko Illustrated Globe
// Contains real country geometries (lat/lng coordinates), centroids, and metadata

export interface CountryGeoData {
  id: string; // ISO 3-letter code or identifier (e.g. "FRA", "JPN", "IND")
  name: string; // Display Name (e.g. "France", "Japan", "India")
  continent: string;
  lat: number;
  lng: number;
  polygons: [number, number][][]; // Polygons array of [lng, lat] vertices
}

// Point in Polygon algorithm helper
export function isPointInPolygon(point: [number, number], polygon: [number, number][]): boolean {
  const [x, y] = point;
  let inside = false;
  for (let i = 0, j = polygon.length - 1; i < polygon.length; j = i++) {
    const xi = polygon[i][0], yi = polygon[i][1];
    const xj = polygon[j][0], yj = polygon[j][1];
    const intersect = ((yi > y) !== (yj > y)) && (x < (xj - xi) * (y - yi) / (yj - yi) + xi);
    if (intersect) inside = !inside;
  }
  return inside;
}

export function isPointInCountry(point: [number, number], country: CountryGeoData): boolean {
  return country.polygons.some((poly) => isPointInPolygon(point, poly));
}

