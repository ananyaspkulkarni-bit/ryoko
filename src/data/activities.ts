// Fast Indexing via HashMap
const activitiesMap = new HashMap<string, Activity[]>();

DESTINATION_ACTIVITIES.forEach((act) => {
  const existing = activitiesMap.get(act.destinationId) || [];
  existing.push(act);
  activitiesMap.set(act.destinationId, existing);
});

/**
 * Checks whether factual, verified activities exist for the given destination ID.
 */
export function hasVerifiedActivitiesForDestination(destinationId: string): boolean {
  if (!destinationId) return false;
  const directMatch = activitiesMap.get(destinationId.toLowerCase());
  return Boolean(directMatch && directMatch.length > 0);
}

/**
 * Returns candidate activities for a destination ID.
 * If destination has curated activities, returns them.
 * For uncurated destinations, returns an empty array.
 * Never fabricates generic placeholder activities or guessed admission prices.
 */
export function getActivitiesForDestination(destinationId: string, _destinationName?: string): Activity[] {
  if (!destinationId) return [];
  const normalizedId = destinationId.toLowerCase();
  const directMatch = activitiesMap.get(normalizedId);
  if (directMatch && directMatch.length > 0) {
    return directMatch;
  }
  return [];
}
